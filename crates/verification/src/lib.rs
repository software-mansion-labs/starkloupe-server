use cairo_lang_starknet_classes::contract_class::ContractClass;
use serde::{Deserialize, Serialize};
use std::collections::HashMap;

pub const SUPPORTED_VERSIONS: &[(u32, u32, u32)] = &[(2, 6, 3), (2, 6, 4), (2, 7, 0)];

#[derive(Debug)]
pub struct VerifiedClassRow {
    pub hash: String,
    pub is_sierra_debug_info: bool,
    pub is_cairo_debug_info: bool,
    pub is_source_code: bool,
    pub chain_id: Option<String>,
    pub project_id: Option<i32>,
}

#[derive(Serialize, Deserialize)]
pub struct VerifiedClassData {
    pub contract_class: ContractClass,
    pub cairo_debug_info: Option<SierraToCairoDebugInfo>,
    pub source_code: HashMap<String, String>,
}

/// Generated by modified Scarb
#[derive(Debug, Serialize, Deserialize)]
pub struct SierraToCairoDebugInfo {
    pub sierra_statements_to_cairo_info: HashMap<usize, SierraStatementToCairoDebugInfo>,
}

#[derive(Debug, Serialize, Deserialize, Clone)]
pub struct SierraStatementToCairoDebugInfo {
    pub cairo_locations: Vec<CodeLocation>,
}

/// Human readable position inside a file, in lines and characters.
#[derive(Debug, Serialize, Clone, Deserialize, Hash, Eq, PartialEq)]
pub struct TextPosition {
    /// Line index, 0 based.
    pub line: usize,
    /// Character index inside the line, 0 based.
    pub col: usize,
}

#[derive(Debug, Serialize, Clone, Deserialize, Hash, Eq, PartialEq)]
pub struct CodeLocation {
    pub start: TextPosition,
    pub end: TextPosition,
    pub file_path: String,
}
